import fs from 'node:fs/promises';
import {Workbook,SpreadsheetFile} from '@oai/artifact-tool';
const outputDir=process.argv[2] ?? new URL('.',import.meta.url).pathname;
const dataDir=process.argv[3] ?? outputDir;
const data=JSON.parse(await fs.readFile(`${dataDir}/bom_data.json`,'utf8'));
const w=Workbook.create();
const s=w.worksheets.add('整机BOM');
s.showGridLines=false;s.tabColor='#243D59';
const headers=['编号','类别','品名','规格 / 设计要求','净用量','单位','必要性','确认状态','供货 / 重复采购提示','装配及采购备注','来源依据','建议备料'];
s.getRange('A2').values=[['VibraReveal V7.3 整机 BOM']];
s.getRange('A3').values=[['2026-10-30｜数量为单台净用量；不是采购冻结清单。用户已有件未知，先盘点再购买。']];
s.getRange('A4').values=[['FPC 按 200 mm；针数、间距、同反向与引脚兼容需核对。20 cm 不代表布线已实测通过。']];
s.getRange('A5').values=[['净用量空白表示待定，不是 0；建议备料未加入净用量。工具/选配/条件项可按“必要性”筛选。']];
s.getRange('A6:L6').values=[headers];
const rows=data.rows.map(r=>[r.id,r.category,r.name,r.spec,r.qty,r.unit,r.need,r.status,r.supply,r.note,r.source,r.spare??'']);
s.getRange(`A7:L${rows.length+6}`).values=rows;
s.getRange(`A1:L${rows.length+6}`).format.font={name:'Arial',size:10,color:'#243447'};
s.getRange('A2').format.font={name:'Arial',size:16,bold:true,color:'#243D59'};
s.getRange(`A7:L${rows.length+6}`).format.wrapText=true;
s.getRange(`A7:L${rows.length+6}`).format.verticalAlignment='center';
s.getRange(`A7:L${rows.length+6}`).format.rowHeight=78;
const widths=[10,16,24,42,10,8,16,24,36,56,45,16];
widths.forEach((v,i)=>s.getRangeByIndexes(0,i,rows.length+6,1).format.columnWidth=v);
rows.forEach((row,i)=>{const lines=Math.max(...row.map((x,j)=>Math.ceil([...String(x??'')].reduce((a,c)=>a+(c.charCodeAt(0)>255?2:1),0)/(widths[j]-2))));s.getRange(`A${i+7}:L${i+7}`).format.rowHeight=Math.max(52,lines*13+12);});
s.getRange('A6:L6').format={fill:'#243D59',font:{name:'Arial',size:10,bold:true,color:'#FFFFFF'},rowHeight:30,wrapText:true};
s.getRange(`E7:E${rows.length+6}`).setNumberFormat('0');
s.freezePanes.freezeRows(6);s.freezePanes.freezeColumns(3);
const t=s.tables.add(`A6:L${rows.length+6}`,true,'CompleteBOM');t.showFilterButton=true;
s.getRange(`H7:H${rows.length+6}`).conditionalFormats.add('containsText',{text:'待',format:{fill:'#FFF2CC'}});
const n=w.worksheets.add('使用与待确认');n.showGridLines=false;
n.getRange('A2').values=[['采购和装配前核对']];
n.getRange('A2').format.font={name:'Arial',size:16,bold:true};
n.getRange('A4:C4').values=[['项目','已知依据与限制','下一步']];
n.getRange(`A5:C${data.notes.length+4}`).values=data.notes;
n.getRange(`A4:C${data.notes.length+4}`).format.font={name:'Arial',size:11,color:'#243447'};
n.getRange(`A5:C${data.notes.length+4}`).format.wrapText=true;
n.getRange(`A5:C${data.notes.length+4}`).format.rowHeight=75;
n.getRange(`A4:C${data.notes.length+4}`).format.verticalAlignment='center';
n.getRange('A1:A30').format.columnWidth=24;n.getRange('B1:B30').format.columnWidth=75;n.getRange('C1:C30').format.columnWidth=65;
n.getRange('A4:C4').format={fill:'#243D59',font:{name:'Arial',size:11,bold:true,color:'#FFFFFF'},rowHeight:28};
n.freezePanes.freezeRows(4);
w.recalculate();
await fs.writeFile(`${outputDir}/workbook_checks.ndjson`,(await w.inspect({kind:'match',searchTerm:'#REF!|#DIV/0!|#VALUE!|#NAME\\?|#NUM!|#SPILL!',options:{useRegex:true,maxResults:100},summary:'error scan'})).ndjson);
console.log((await w.inspect({kind:'table',range:'整机BOM!A6:H12',tableMaxRows:7,tableMaxCols:8,maxChars:3000})).ndjson);
for(const [sheetName,range,filename] of [['整机BOM','A2:H12','preview_bom.png'],['使用与待确认','A2:C10','preview_notes.png']]){
 const p=await w.render({sheetName,range,scale:1,format:'png'});await fs.writeFile(`${outputDir}/${filename}`,new Uint8Array(await p.arrayBuffer()));
}
await (await SpreadsheetFile.exportXlsx(w)).save(`${outputDir}/VibraReveal_V7.3_整机完整BOM.xlsx`);
console.log(JSON.stringify({rows:rows.length,outputDir}));
